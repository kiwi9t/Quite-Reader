// src/agents/parserAnalyzerAgent.ts

import type { ReadingAsstState, ChapterAnalysisResult } from "../state";
import type { MinimalLLMClient } from "../llm/types";
import { invokeWithStructuredOutput } from "../llm/structuredOutput";
import { ChapterAnalysisResultSchema } from "../schemas/readingSchemas";

/**
 * System instruction for Parser & Content Analyzer Agent.
 * Parser & Content Analyzer Agent 的系统级指令。
 *
 * This agent selects only the words that are likely to block this specific user's
 * understanding of the chapter.
 *
 * 这个 Agent 只筛选出真正可能阻碍当前用户理解章节的词。
 */
export const PARSER_ANALYZER_SYSTEM_PROMPT = `
You are Parser & Content Analyzer Agent for a second-language ebook reading companion system.

Your job is NOT to list every difficult word.

Your job is to select only the "core obstacle words" that are likely to block this specific user's understanding of the current chapter.

You will receive:
1. A user language profile generated by UserProfilerAgent.
2. The current chapter title.
3. The current chapter content.

You must use the user's profile to adapt your filtering.

Definition:

A "core obstacle word" is a word or phrase that:
- affects the main action of a sentence,
- changes the emotional tone,
- explains a character's motivation,
- carries cause-effect logic,
- marks contrast, concession, or condition,
- is culturally or historically loaded,
- or prevents the user from understanding what is happening.

A "guessable word" is a word that:
- may be unknown to the user,
- but is not essential for understanding the sentence,
- or can be safely inferred from nearby context,
- or is a decorative detail that does not affect the main meaning.

Selection rules:

1. Prioritize words that match the user's focusWordTypes.
   For example, if the user struggles with "core verbs", prioritize verbs that carry the main action.

2. Prioritize words related to the user's commonErrorTypes.
   For example, if the user has "connector_misread", prioritize words such as although, despite, nevertheless, whereas, yet.

3. Do not select a word only because it is rare.
   Rarity alone is not enough.

4. Do not select proper nouns unless they are culturally important or confusing in context.

5. Do not select decorative adjectives unless they change emotional tone or plot understanding.

6. Do not select words that the user can safely ignore without losing the main idea.

7. Explain each selected word in context, not as a dictionary definition.

8. Keep the output compact. Prefer 5-12 core obstacle words for a normal chapter excerpt.

Return strictly valid JSON only.
Do not wrap the JSON in Markdown.
Do not add comments.

The JSON object must match this shape:

{
  "coreObstacleWords": [
    {
      "text": string,
      "sentence": string,
      "meaningInContextZh": string,
      "whyItMatters": string,
      "wordType": string,
      "severity": "low" | "medium" | "high",
      "guessableFromContext": boolean
    }
  ],
  "skippedGuessableWords": [
    {
      "text": string,
      "reason": string
    }
  ],
  "filteringSummary": string
}
`;

/**
 * Build the user message for Parser & Content Analyzer Agent.
 * 构造发送给 Parser & Content Analyzer Agent 的用户消息。
 */
export function buildParserAnalyzerPrompt(state: ReadingAsstState): string {
  if (!state.userProfile) {
    throw new Error(
      "ParserAnalyzerAgent requires state.userProfile. Run UserProfilerAgent first."
    );
  }

  if (!state.chapterInput) {
    throw new Error(
      "ParserAnalyzerAgent requires state.chapterInput. Provide chapter content first."
    );
  }

  return `
Analyze the following chapter for this specific user.

User profile:
${JSON.stringify(state.userProfile, null, 2)}

Chapter title:
${state.chapterInput.title}

Chapter content:
${state.chapterInput.content}

Task:
Select only the core obstacle words that are likely to block this user's understanding.

Return JSON only.
`;
}

/**
 * Parser & Content Analyzer Agent node.
 * Parser & Content Analyzer Agent 节点。
 *
 * It reads:
 * 它读取：
 * - state.userProfile
 * - state.chapterInput
 *
 * It writes:
 * 它写入：
 * - state.analysisResult
 */
export async function parserAnalyzerAgentNode(
  state: ReadingAsstState,
  llm: MinimalLLMClient
): Promise<Partial<ReadingAsstState>> {
  const userPrompt = buildParserAnalyzerPrompt(state);

  const analysisResult = await invokeWithStructuredOutput<ChapterAnalysisResult>({
    agentName: "ParserAnalyzerAgent",
    llm,
    systemPrompt: PARSER_ANALYZER_SYSTEM_PROMPT,
    userPrompt,
    schema: ChapterAnalysisResultSchema,
  });

  return {
    analysisResult,
  };
}
