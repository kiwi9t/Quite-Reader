/**
 * User feedback on a test sentence.
 * 用户对测试句子的反馈。
 *
 * This helps UserProfilerAgent infer concrete blockers,
 * such as unknown core verbs, connector misreading, or long sentence parsing.
 *
 * 这可以帮助 UserProfilerAgent 推断具体阻碍，
 * 例如核心动词不认识、连接词误读、长句结构解析困难等。
 */
export interface TestSentenceFeedback {
  /**
   * The original test sentence shown to the user.
   * 展示给用户的原始测试句。
   */
  sentence: string;

  /**
   * User's reaction or explanation after reading the sentence.
   * 用户读完句子后的反馈或解释。
   */
  userFeedback: string;
}

/**
 * User's raw input.
 * 用户输入的原始信息。
 */
export interface UserInput {
  /**
   * User's standardized English test score, written as free text.
   * 用户的标准化英语考试成绩，保留为自由文本。
   */
  testScore: string;

  /**
   * User's self-reported reading difficulties.
   * 用户自述的阅读难点。
   */
  selfReportedDifficulties: string[];

  /**
   * User's feedback on diagnostic test sentences.
   * 用户对诊断测试句的反馈。
   */
  testSentenceFeedback: TestSentenceFeedback[];
}

/**
 * AI-generated language profile.
 * AI 生成的用户语言画像。
 */
export interface UserProfile {
  /**
   * Estimated vocabulary size.
   * 预估词汇量。
   */
  estimatedVocabularySize: number;

  /**
   * Estimated CEFR level range.
   * 预估 CEFR 等级区间。
   */
  estimatedCEFR: string;

  /**
   * Word types that downstream agents should prioritize.
   * 后续 Agent 需要优先标注的词汇类型。
   */
  focusWordTypes: string[];

  /**
   * Common reading error types inferred from user input.
   * 从用户输入中推断出的高频阅读错误类型。
   */
  commonErrorTypes: string[];

  /**
   * Confidence score of this profile.
   * 当前画像的置信度。
   *
   * 0 means very uncertain, 1 means highly confident.
   * 0 表示非常不确定，1 表示高度确定。
   */
  confidence: number;
}

/**
 * Input chapter content.
 * 当前要分析的章节内容。
 */
export interface ChapterInput {
  /**
   * Chapter title.
   * 章节标题。
   */
  title: string;

  /**
   * Plain text or markdown content of the current chapter.
   * 当前章节的纯文本或 Markdown 内容。
   *
   * In later steps, EPUB/MOBI parsing will convert book files into this format.
   * 后续步骤中，EPUB/MOBI 解析器会把书籍文件转换成这个格式。
   */
  content: string;
}

/**
 * A word or phrase that may block the user's reading comprehension.
 * 可能阻碍用户阅读理解的词或短语。
 */
export interface CoreObstacleWord {
  /**
   * The exact word or phrase from the chapter.
   * 章节中出现的原词或短语。
   */
  text: string;

  /**
   * The sentence where the word appears.
   * 该词所在的原句。
   */
  sentence: string;

  /**
   * Context-specific meaning in Chinese.
   * 结合上下文的中文释义。
   */
  meaningInContextZh: string;

  /**
   * Why this word matters for understanding the sentence or paragraph.
   * 为什么这个词会影响句子或段落理解。
   */
  whyItMatters: string;

  /**
   * Word type category.
   * 词汇类型。
   */
  wordType: string;

  /**
   * Importance level for this user's reading.
   * 对当前用户阅读的阻碍程度。
   */
  severity: "low" | "medium" | "high";

  /**
   * Whether the word is guessable from context.
   * 是否可以通过上下文大致猜出。
   */
  guessableFromContext: boolean;
}

/**
 * Result generated by Parser & Content Analyzer Agent.
 * Parser & Content Analyzer Agent 生成的分析结果。
 */
export interface ChapterAnalysisResult {
  /**
   * Core obstacle words selected for this specific user.
   * 针对当前用户筛选出的核心障碍词。
   */
  coreObstacleWords: CoreObstacleWord[];

  /**
   * Words that looked difficult but were intentionally skipped.
   * 看起来可能难，但被有意过滤掉的词。
   */
  skippedGuessableWords: Array<{
    /**
     * The skipped word or phrase.
     * 被跳过的词或短语。
     */
    text: string;

    /**
     * Why this word was skipped.
     * 为什么这个词被跳过。
     */
    reason: string;
  }>;

  /**
   * Short explanation of the filtering strategy.
   * 本次筛选策略说明。
   */
  filteringSummary: string;
}

/**
 * User's current reading progress.
 * 用户当前阅读进度。
 *
 * This is used for timeline isolation.
 * 这个字段用于时间线隔离，防止后续剧情剧透。
 */
export interface ReadingProgress {
  /**
   * Book title.
   * 书名。
   */
  bookTitle: string;

  /**
   * Current chapter index, starting from 1.
   * 当前章节序号，从 1 开始。
   */
  currentChapterIndex: number;

  /**
   * Current chapter title.
   * 当前章节标题。
   */
  currentChapterTitle: string;

  /**
   * Optional safe summary of previous chapters only.
   * 仅包含已读章节的安全摘要。
   *
   * This must not include any future plot information.
   * 这里绝对不能包含未来剧情信息。
   */
  safePreviousSummary?: string;
}

/**
 * A background concept that is safe to explain.
 * 可以安全解释的背景概念。
 */
export interface NonSpoilerContextItem {
  /**
   * The concept, place, object, phrase, cultural reference, or relationship.
   * 概念、地点、物品、表达、文化引用或人物关系。
   */
  topic: string;

  /**
   * Category of the background explanation.
   * 背景解释分类。
   */
  category:
    | "historical_geographical"
    | "cultural_reference"
    | "idiom_or_expression"
    | "character_relationship"
    | "setting_or_worldbuilding"
    | "literary_style"
    | "other";

  /**
   * Non-spoiler explanation in Chinese.
   * 中文无剧透解释。
   */
  explanationZh: string;

  /**
   * Why this is useful for the current chapter.
   * 为什么这对理解当前章节有帮助。
   */
  whyUsefulNow: string;

  /**
   * Confidence that this explanation is safe and non-spoiling.
   * 对该解释无剧透安全性的置信度。
   */
  spoilerSafetyConfidence: number;
}

/**
 * Result generated by Non-Spoiler Context Agent.
 * Non-Spoiler Context Agent 生成的结果。
 */
export interface NonSpoilerContextResult {
  /**
   * Short non-spoiler guide for the current reading position.
   * 针对当前阅读进度的简短无剧透导读。
   */
  nonSpoilerGuideZh: string;

  /**
   * Safe background items.
   * 安全背景知识条目。
   */
  contextItems: NonSpoilerContextItem[];

  /**
   * Topics intentionally skipped because they may require future plot knowledge.
   * 因可能涉及未来剧情而有意跳过的话题。
   */
  skippedPotentialSpoilers: Array<{
    /**
     * Topic that was skipped.
     * 被跳过的话题。
     */
    topic: string;

    /**
     * Why the topic was skipped.
     * 为什么该话题被跳过。
     */
    reason: string;
  }>;

  /**
   * Safety note explaining the timeline boundary used.
   * 安全说明：本次采用的时间线边界。
   */
  timelineBoundaryNote: string;
}

/**
 * Shared workflow state.
 * 工作流中的共享状态。
 *
 * You can think of this as a shared notebook passed between agents.
 * 可以把它理解成多个 Agent 之间传递的“共享笔记本”。
 */
export interface ReadingAsstState {
  /**
   * Raw user input.
   * 用户输入的基础信息。
   */
  userInput: UserInput;

  /**
   * Result generated by UserProfilerAgent.
   * UserProfilerAgent 生成的用户画像。
   *
   * It is null before the profiling agent runs.
   * 在画像 Agent 执行前，这里是 null。
   */
  userProfile: UserProfile | null;

  /**
   * Current chapter input.
   * 当前章节输入。
   *
   * It is null before a chapter is loaded.
   * 在章节载入前，这里是 null。
   */
  chapterInput: ChapterInput | null;

  /**
   * Result generated by Parser & Content Analyzer Agent.
   * Parser & Content Analyzer Agent 生成的章节分析结果。
   *
   * It is null before the analyzer agent runs.
   * 在文本分析 Agent 执行前，这里是 null。
   */
  analysisResult: ChapterAnalysisResult | null;

  /**
   * User's current reading progress.
   * 用户当前阅读进度。
   *
   * It is null before reading progress is set.
   * 在设置阅读进度前，这里是 null。
   */
  readingProgress: ReadingProgress | null;

  /**
   * Result generated by Non-Spoiler Context Agent.
   * Non-Spoiler Context Agent 生成的无剧透背景知识。
   *
   * It is null before the context agent runs.
   * 在无剧透背景 Agent 执行前，这里是 null。
   */
  nonSpoilerContext: NonSpoilerContextResult | null;
}

/**
 * Initial state of the reading assistant workflow.
 * 阅读助手工作流的初始状态。
 */
export const initialReadingState: ReadingAsstState = {
  userInput: {
    testScore: "",
    selfReportedDifficulties: [],
    testSentenceFeedback: [],
  },

  userProfile: null,

  chapterInput: null,

  analysisResult: null,

  readingProgress: null,

  nonSpoilerContext: null,
};